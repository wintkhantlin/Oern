#!/usr/bin/env node
// Turns data/yutra_raw/signal_delay_observations.csv into a typed module the
// planner can import in both the server and the browser. Run after the CSV
// changes:  node scripts/build-yutra-data.mjs
import { readFileSync, writeFileSync } from "node:fs";

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(cell);
      cell = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(cell);
      cell = "";
      if (row.some((c) => c !== "")) rows.push(row);
      row = [];
    } else cell += ch;
  }
  if (cell !== "" || row.length) {
    row.push(cell);
    rows.push(row);
  }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const source = "data/yutra_raw/signal_delay_observations.csv";
const rows = parseCsv(readFileSync(source, "utf8"));
const out = rows.map((r) => ({
  id: `yutra-signal-${r.signal_id}`,
  name: r.intersection_name,
  township: r.township,
  latitude: Number(r.latitude),
  longitude: Number(r.longitude),
  cycleSeconds: Number(r.cycle_length_seconds),
  meanDelaySeconds: Number(r.mean_delay_seconds),
  dataType: r.data_type,
  confidence: r.confidence,
  surveyYear: Number(r.survey_year),
  sourcePage: r.source_page,
  tableId: r.table_id,
}));
for (const s of out)
  if (![s.latitude, s.longitude, s.meanDelaySeconds].every(Number.isFinite))
    throw new Error(`Bad row ${s.id}`);

writeFileSync(
  "src/lib/delivery/data/yutra-signal-delays.ts",
  `// GENERATED by scripts/build-yutra-data.mjs from ${source}. Do not edit.
// YUTRA (Yangon Urban Transport) survey: measured mean control delay per signal.

export type YutraSignalDelay = {
  id: string;
  name: string;
  township: string;
  latitude: number;
  longitude: number;
  cycleSeconds: number;
  meanDelaySeconds: number;
  dataType: string;
  confidence: string;
  surveyYear: number;
  sourcePage: string;
  tableId: string;
};

export const YUTRA_SIGNAL_DELAYS: readonly YutraSignalDelay[] = ${JSON.stringify(out, null, 2)};
`,
);
console.log(`Wrote ${out.length} signals`);


// ---- Congestion, volumes and road speeds -------------------------------------
const num = (v) => (v === "" || v == null ? null : Number(v));
const volumes = parseCsv(readFileSync("data/yutra_raw/intersection_volume.csv", "utf8"));
const where = new Map(volumes.map((v) => [v.intersection_name, v]));
const congestion = parseCsv(readFileSync("data/yutra_raw/intersection_congestion.csv", "utf8"))
  .map((r) => {
    const at = where.get(r.intersection_name);
    if (!at) return null;
    const vol = volumes.find(
      (v) => v.intersection_name === r.intersection_name && v.time_period === r.time_period,
    );
    return {
      name: r.intersection_name,
      township: r.township,
      latitude: Number(at.latitude),
      longitude: Number(at.longitude),
      period: r.time_period.startsWith("Peak") ? "peak" : "offpeak",
      level: r.congestion_level.toLowerCase(),
      volumeVehPerHour: vol ? num(vol.volume_veh_hour) : null,
      confidence: r.confidence,
      dataType: r.data_type,
      surveyYear: Number(r.survey_year),
    };
  })
  .filter(Boolean);
const roads = parseCsv(readFileSync("data/yutra_raw/road_speed_capacity.csv", "utf8")).map((r) => ({
  road: r.road_name,
  township: r.township,
  roadClass: r.road_class,
  direction: r.direction,
  maxSpeedKmh: num(r.max_speed_kmh),
  capacityVehPerHour: num(r.capacity_veh_hour),
  confidence: r.confidence,
  surveyYear: Number(r.survey_year),
}));
writeFileSync(
  "src/lib/delivery/data/yutra-network.ts",
  `// GENERATED by scripts/build-yutra-data.mjs from data/yutra_raw/*.csv. Do not edit.
// YUTRA 2013 survey: junction congestion by period (joined to surveyed
// coordinates) and road speed/capacity limits.

export type YutraCongestion = {
  name: string;
  township: string;
  latitude: number;
  longitude: number;
  period: "peak" | "offpeak";
  level: "low" | "medium" | "high";
  volumeVehPerHour: number | null;
  confidence: string;
  dataType: string;
  surveyYear: number;
};

export type YutraRoad = {
  road: string;
  township: string;
  roadClass: string;
  direction: string;
  maxSpeedKmh: number | null;
  capacityVehPerHour: number | null;
  confidence: string;
  surveyYear: number;
};

export const YUTRA_CONGESTION: readonly YutraCongestion[] = ${JSON.stringify(congestion, null, 2)};

export const YUTRA_ROADS: readonly YutraRoad[] = ${JSON.stringify(roads, null, 2)};
`,
);
